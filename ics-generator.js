/**
 * ICS File Generator for World Cup 2026 Matches
 * Generates RFC 5545 compliant iCalendar files
 */

class ICSGenerator {
    constructor() {
        this.prodId = '-//World Cup 2026 Calendar//EN';
        this.version = '2.0';
    }

    /**
     * Generate ICS file content for multiple matches
     * @param {Array} matches - Array of match objects
     * @param {string} timezone - IANA timezone identifier
     * @returns {string} ICS file content
     */
    generateICS(matches, timezone = 'America/New_York') {
        const lines = [
            'BEGIN:VCALENDAR',
            'VERSION:' + this.version,
            'PRODID:' + this.prodId,
            'CALSCALE:GREGORIAN',
            'METHOD:PUBLISH',
            'X-WR-CALNAME:FIFA World Cup 2026',
            'X-WR-TIMEZONE:' + timezone,
            'X-WR-CALDESC:FIFA World Cup 2026 Match Schedule'
        ];

        matches.forEach(match => {
            lines.push(...this.generateEvent(match, timezone));
        });

        lines.push('END:VCALENDAR');
        
        return lines.join('\r\n');
    }

    /**
     * Generate a single event for a match
     * @param {Object} match - Match object
     * @param {string} timezone - IANA timezone identifier
     * @returns {Array} Array of ICS lines for the event
     */
    generateEvent(match, timezone) {
        const startDate = new Date(match.date);
        const endDate = new Date(startDate.getTime() + (2 * 60 * 60 * 1000)); // 2 hours duration
        
        const lines = [
            'BEGIN:VEVENT',
            'UID:' + match.id + '@worldcup2026.com',
            'DTSTAMP:' + this.formatICSDate(new Date()),
            'DTSTART:' + this.formatICSDate(startDate),
            'DTEND:' + this.formatICSDate(endDate),
            'SUMMARY:' + this.escapeText(this.formatMatchTitle(match)),
            'DESCRIPTION:' + this.escapeText(this.formatDescription(match)),
            'LOCATION:' + this.escapeText(this.formatLocation(match)),
            'TRANSP:TRANSPARENT',
            'STATUS:CONFIRMED',
            'SEQUENCE:0',
            'X-MICROSOFT-CDO-BUSYSTATUS:FREE'
        ];

        // Add alarm/reminder (15 minutes before)
        lines.push(
            'BEGIN:VALARM',
            'TRIGGER:-PT15M',
            'ACTION:DISPLAY',
            'DESCRIPTION:Match starts in 15 minutes',
            'END:VALARM'
        );

        lines.push('END:VEVENT');
        
        return lines;
    }

    /**
     * Format match title with team names and flags
     * @param {Object} match - Match object
     * @returns {string} Formatted title
     */
    formatMatchTitle(match) {
        return `${match.team1.flag} ${match.team1.name} vs ${match.team2.name} ${match.team2.flag}`;
    }

    /**
     * Format match description with details
     * @param {Object} match - Match object
     * @returns {string} Formatted description
     */
    formatDescription(match) {
        const lines = [
            `FIFA World Cup 2026 - ${match.stage}`,
            '',
            `${match.team1.flag} ${match.team1.name} vs ${match.team2.name} ${match.team2.flag}`,
            ''
        ];

        // Add custom description for special events (Opening Ceremonies, Halftime Show)
        if (match.description) {
            lines.push(match.description);
            lines.push('');
        }

        if (match.group) {
            lines.push(`Group: ${match.group}`);
            lines.push('');
        }

        lines.push(
            `Stadium: ${match.stadium}`,
            `Location: ${match.city}, ${match.country}`,
            ''
        );

        if (match.broadcast && match.broadcast.length > 0) {
            // Replace "Tele" with "Telemundo"
            const broadcastChannels = match.broadcast.map(channel =>
                channel === 'Tele' ? 'Telemundo' : channel
            );
            lines.push(`Watch on: ${broadcastChannels.join(', ')}`);
            lines.push('');
        }

        lines.push('Generated by IBM Bob - Match Sources: World Cup 2026 Calendar App');

        return lines.join('\n');
    }

    /**
     * Format location string
     * @param {Object} match - Match object
     * @returns {string} Formatted location
     */
    formatLocation(match) {
        return `${match.stadium}, ${match.city}, ${match.country}`;
    }

    /**
     * Format date to ICS format (YYYYMMDDTHHMMSSZ)
     * @param {Date} date - JavaScript Date object
     * @returns {string} ICS formatted date
     */
    formatICSDate(date) {
        const pad = (num) => String(num).padStart(2, '0');
        
        return date.getUTCFullYear() +
               pad(date.getUTCMonth() + 1) +
               pad(date.getUTCDate()) +
               'T' +
               pad(date.getUTCHours()) +
               pad(date.getUTCMinutes()) +
               pad(date.getUTCSeconds()) +
               'Z';
    }

    /**
     * Escape special characters for ICS format
     * @param {string} text - Text to escape
     * @returns {string} Escaped text
     */
    escapeText(text) {
        return text
            .replace(/\\/g, '\\\\')
            .replace(/;/g, '\\;')
            .replace(/,/g, '\\,')
            .replace(/\n/g, '\\n');
    }

    /**
     * Download ICS file
     * @param {string} content - ICS file content
     * @param {string} filename - Filename for download
     */
    downloadICS(content, filename = 'world-cup-2026.ics') {
        const blob = new Blob([content], { type: 'text/calendar;charset=utf-8' });
        const link = document.createElement('a');
        link.href = URL.createObjectURL(blob);
        link.download = filename;
        
        // Trigger download
        document.body.appendChild(link);
        link.click();
        document.body.removeChild(link);
        
        // Clean up
        URL.revokeObjectURL(link.href);
    }

    /**
     * Generate and download ICS for all matches
     * @param {Array} matches - Array of match objects
     * @param {string} timezone - IANA timezone identifier
     */
    downloadAllMatches(matches, timezone) {
        const content = this.generateICS(matches, timezone);
        this.downloadICS(content, 'world-cup-2026-all-matches.ics');
    }

    /**
     * Generate and download ICS for selected matches
     * @param {Array} matches - Array of match objects
     * @param {string} timezone - IANA timezone identifier
     */
    downloadSelectedMatches(matches, timezone) {
        if (matches.length === 0) {
            alert('Please select at least one match to download.');
            return;
        }
        
        const content = this.generateICS(matches, timezone);
        const filename = matches.length === 1 
            ? 'world-cup-2026-match.ics'
            : `world-cup-2026-${matches.length}-matches.ics`;
        
        this.downloadICS(content, filename);
    }
}

// Export for use in app.js
if (typeof module !== 'undefined' && module.exports) {
    module.exports = ICSGenerator;
}

